document.addEventListener('DOMContentLoaded', () => {
    const langSelect = document.getElementById('langSelect');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => {
            updateDashboardLanguage(e.target.value);
        });
    }
});

function updateDashboardLanguage(lang) {
    const dict = i18nTranslations[lang] || i18nTranslations.en;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerText = dict[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });
}

function detectGPSLocation() {
    if (!navigator.geolocation) {
        alert("Geolocation API is not supported by your browser. You can select your location manually.");
        return;
    }

    const locBtn = document.getElementById('btnDetectLocation');
    if (locBtn) locBtn.innerHTML = '<span class="spinner-border spinner-border-sm me-1"></span> Locating...';

    navigator.geolocation.getCurrentPosition(
        (position) => {
            const lat = position.coords.latitude;
            const lon = position.coords.longitude;

            fetch(`https://nominatim.openstreetmap.org/reverse?lat=${lat}&lon=${lon}&format=json`)
                .then(res => res.json())
                .then(data => {
                    let locName = "Vijayawada, Andhra Pradesh";
                    if (data && data.address) {
                        const city = data.address.city || data.address.town || data.address.county || "Vijayawada";
                        const state = data.address.state || "Andhra Pradesh";
                        locName = `${city}, ${state}`;
                    }
                    saveLocationBackend(lat, lon, locName);
                })
                .catch(() => {
                    saveLocationBackend(lat, lon, `Lat ${lat.toFixed(2)}, Lon ${lon.toFixed(2)}`);
                });
        },
        (error) => {
            if (locBtn) locBtn.innerHTML = '<i class="bi bi-crosshair me-1"></i> GPS Detect';
            alert("Unable to access your GPS location. Please enable location permissions or select your farm location manually.");
        },
        { timeout: 8000 }
    );
}

function saveLocationBackend(lat, lon, locationName) {
    fetch('/api/location', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ latitude: lat, longitude: lon, location_name: locationName })
    })
    .then(res => res.json())
    .then(data => {
        if (data.success) {
            const summaryLoc = document.getElementById('summaryLocation');
            const weatherLoc = document.getElementById('weatherLocHeader');
            if (summaryLoc) summaryLoc.innerText = locationName;
            if (weatherLoc) weatherLoc.innerText = locationName;

            // Refresh weather
            fetch(`/api/weather?lat=${lat}&lon=${lon}&location=${encodeURIComponent(locationName)}`)
                .then(r => r.json())
                .then(wData => {
                    const temp = document.getElementById('wTemp');
                    const cond = document.getElementById('wCondition');
                    const hum = document.getElementById('wHumidity');
                    const rain = document.getElementById('wRainProb');
                    const wind = document.getElementById('wWind');
                    const alertText = document.getElementById('wAlertText');

                    if (temp) temp.innerText = wData.temperature;
                    if (cond) cond.innerText = wData.condition;
                    if (hum) hum.innerText = `${wData.humidity}%`;
                    if (rain) rain.innerText = `${wData.rain_probability}%`;
                    if (wind) wind.innerText = `${wData.wind_speed} km/h`;
                    if (alertText) alertText.innerText = wData.alert;
                });
        }

        const locBtn = document.getElementById('btnDetectLocation');
        if (locBtn) locBtn.innerHTML = '<i class="bi bi-check-circle-fill me-1"></i> Located';
    });
}

function saveManualLocation() {
    const locSelect = document.getElementById('manualLocationSelect');
    const cropSelect = document.getElementById('manualCropSelect');
    if (!locSelect) return;

    const locName = locSelect.value;
    const cropName = cropSelect ? cropSelect.value : "Paddy";

    saveLocationBackend(16.5062, 80.6480, locName);

    const summaryCropName = document.getElementById('summaryCropName');
    if (summaryCropName) summaryCropName.innerText = cropName;

    // Close modal
    const modalEl = document.getElementById('locationModal');
    if (modalEl && window.bootstrap) {
        const modal = bootstrap.Modal.getInstance(modalEl);
        if (modal) modal.hide();
    }
}

function setQueryText(text) {
    const input = document.getElementById('agronomistQueryInput');
    if (input) input.value = text;
}

function askAIAgronomist() {
    const input = document.getElementById('agronomistQueryInput');
    if (!input || !input.value.strip ? !input.value.trim() : !input.value) return;

    const query = input.value.trim();
    const langSelect = document.getElementById('langSelect');
    const lang = langSelect ? langSelect.value : 'en';

    const btnAsk = document.getElementById('btnAskAI');
    if (btnAsk) btnAsk.disabled = true;

    fetch('/api/voice/query', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ query: query, lang: lang })
    })
    .then(res => res.json())
    .then(data => {
        if (btnAsk) btnAsk.disabled = false;
        const aiBox = document.getElementById('aiResponseBox');
        const aiText = document.getElementById('aiRespText');
        const aiLang = document.getElementById('aiRespLang');

        if (aiBox && aiText) {
            aiText.innerText = data.response;
            if (aiLang) aiLang.innerText = `Language: ${lang.toUpperCase()}`;
            aiBox.classList.remove('d-none');
        }
    })
    .catch(() => {
        if (btnAsk) btnAsk.disabled = false;
    });
}
